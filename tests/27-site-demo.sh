#!/bin/sh
#
# 27-site-demo.sh — assert scripts/site-demo.sh publishes the playground and the
# library it imports, keeps the homelab nav marker, and does not publish the
# local studio.
# Tier: portable.
set -eu

DIRECTORY_SCRIPT=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
REPOSITORY_ROOT=$(CDPATH= cd -- "$DIRECTORY_SCRIPT/.." && pwd)
. "$DIRECTORY_SCRIPT/lib/test_helpers.sh"

fail() {
    echo "27-site-demo: $1" >&2
    exit 1
}

DIRECTORY_TEST=$(test_output_directory)
mkdir -p "$DIRECTORY_TEST/site.out"

sh "$REPOSITORY_ROOT/scripts/site-demo.sh" "$DIRECTORY_TEST/site.out" \
    || fail 'site-demo.sh failed'

for file_expected in \
    "$DIRECTORY_TEST/site.out/browser/playground.html" \
    "$DIRECTORY_TEST/site.out/browser/demo.mjs" \
    "$DIRECTORY_TEST/site.out/browser/sample.json" \
    "$DIRECTORY_TEST/site.out/krank.mjs" \
    "$DIRECTORY_TEST/site.out/ruleset-run.mjs" \
    "$DIRECTORY_TEST/site.out/ruleset-render.mjs"; do
    [ -f "$file_expected" ] || fail "missing $file_expected"
done

for file_absent in \
    "$DIRECTORY_TEST/site.out/browser/index.html" \
    "$DIRECTORY_TEST/site.out/browser/studio.mjs" \
    "$DIRECTORY_TEST/site.out/browser/catalog.json" \
    "$DIRECTORY_TEST/site.out/browser/files.json"; do
    [ ! -e "$file_absent" ] || fail "the studio is published: $file_absent"
done

head -1 "$DIRECTORY_TEST/site.out/browser/playground.html" | grep -q 'generated by scripts/site-demo.sh' \
    || fail 'playground.html is not marked generated'
grep -q 'HOMELAB-NAV' "$DIRECTORY_TEST/site.out/browser/playground.html" \
    || fail 'playground.html has no HOMELAB-NAV marker'

grep -q '^browser/playground.html|Playground$' "$REPOSITORY_ROOT/site.in/pages.nav" \
    || fail 'site.in/pages.nav does not declare the playground page'
if grep -q '^browser/index.html' "$REPOSITORY_ROOT/site.in/pages.nav"; then
    fail 'site.in/pages.nav still declares the studio page'
fi

test_output_cleanup "$DIRECTORY_TEST"
echo '27-site-demo: ok'
exit 0
