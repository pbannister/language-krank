#!/bin/sh
#
# site-demo.sh: publish the browser demo in the project pages.
#
# The demo lives in sources/browser/ and imports ../krank.mjs. The published copy
# is site.out/browser/, with the library modules it imports at site.out/, so the
# same relative import resolves. The demo page is listed in site.in/pages.nav, so
# the homelab adds it to the one navigation bar at the right depth.
#
# The demo ships with the project pages and not in the npm package: package.json's
# "files" lists the library only.
#
# Usage: sh scripts/site-demo.sh [output-directory]
set -eu

DIRECTORY_SCRIPT=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
REPOSITORY_ROOT=$(CDPATH= cd -- "$DIRECTORY_SCRIPT/.." && pwd)

DIRECTORY_OUTPUT=${1:-"$REPOSITORY_ROOT/site.out"}
DIRECTORY_DEMO="$REPOSITORY_ROOT/sources/browser"

if [ ! -d "$DIRECTORY_DEMO" ]; then
    echo "site-demo: demo directory not found: $DIRECTORY_DEMO" >&2
    exit 1
fi
if [ ! -d "$DIRECTORY_OUTPUT" ]; then
    echo "site-demo: output directory not found: $DIRECTORY_OUTPUT (run the site build first)" >&2
    exit 1
fi

mkdir -p "$DIRECTORY_OUTPUT/browser"

# The page carries the generated marker and keeps the homelab nav marker, so the
# homelab injects the one navigation bar at the page's depth.
{
    echo '<!-- generated by scripts/site-demo.sh; do not edit manually -->'
    cat "$DIRECTORY_DEMO/index.html"
} > "$DIRECTORY_OUTPUT/browser/index.html"

for file_asset in "$DIRECTORY_DEMO/demo.mjs" "$DIRECTORY_DEMO/sample.json"; do
    cp "$file_asset" "$DIRECTORY_OUTPUT/browser/"
done

for file_library in krank.mjs ruleset-run.mjs ruleset-render.mjs; do
    cp "$REPOSITORY_ROOT/sources/$file_library" "$DIRECTORY_OUTPUT/"
done

echo "site-demo: published $DIRECTORY_OUTPUT/browser/ and the library modules into $DIRECTORY_OUTPUT"
